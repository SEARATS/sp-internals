using System.Security;
using System.Text;
using System.Text.Json;
using Mono.Cecil;

if (args.Length < 2)
{
    Console.Error.WriteLine("Usage: Generate <output.cs> <assembly.dll> [assembly.dll ...]");
    return 1;
}

try
{
    Generate(args[0], args[1..]);
    return 0;
}
catch (Exception error)
{
    Console.Error.WriteLine(error.Message);
    return 1;
}

static void Generate(string output, string[] inputs)
{
    var source = new StringBuilder()
        .AppendLine("// <auto-generated/>")
        .AppendLine("#pragma warning disable CS0108 // Metadata names can hide members of object.")
        .AppendLine("using System;")
        .AppendLine("using System.Reflection;")
        .AppendLine("namespace SP.Internals.Generated;");
    var names = new Identifiers();
    var identities = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

    foreach (var input in inputs.Order(StringComparer.Ordinal))
    {
        using var assembly = AssemblyDefinition.ReadAssembly(input);
        if (assembly.Modules.Count != 1)
            throw new InvalidOperationException($"Expected a single-module assembly in '{input}'.");
        if (!identities.Add(assembly.Name.Name))
            throw new InvalidOperationException($"Duplicate assembly name '{assembly.Name.Name}'.");

        var module = assembly.MainModule;
        var types = module.GetTypes().Where(type => type.Name != "<Module>")
            .OrderBy(type => type.FullName, StringComparer.Ordinal).ToArray();
        var assemblyId = names.Take(assembly.Name.Name);
        source.AppendLine($$"""
            #if SP_INTERNALS_EMBEDDED
            internal
            #else
            public
            #endif
            static class {{assemblyId}}
            {
                private static readonly AssemblyBinding Binding = new({{JsonSerializer.Serialize(assembly.Name.Name)}}, new Guid("{{module.Mvid}}"));
            """);

        var typeNames = new Identifiers(assemblyId, "Binding", "Type", "Fields", "Methods", "Constructors", "Properties", "Events");
        var count = 0;
        foreach (var type in types)
        {
            var typeId = typeNames.Take(type.FullName);
            source.AppendLine($$"""
                    /// <summary>{{Xml(type.FullName)}}</summary>
                    public static class {{typeId}}
                    {
                        public static readonly TypeBinding Type = new(Binding, {{Token(type)}});
                """);
            count += Group(source, "Fields", "FieldInfo", type.Fields);
            count += Group(source, "Methods", "MethodInfo", type.Methods.Where(method => !method.IsConstructor));
            count += Group(source, "Constructors", "ConstructorInfo", type.Methods.Where(method => method.IsConstructor));
            count += Group(source, "Properties", "PropertyInfo", type.Properties);
            count += Group(source, "Events", "EventInfo", type.Events);
            source.AppendLine("    }");
        }
        source.AppendLine("}");
        Console.WriteLine($"{assembly.Name.Name}: {types.Length:N0} types, {count:N0} members");
    }

    var generated = source.ToString();
    if (File.Exists(output) && File.ReadAllText(output) == generated)
        return;
    Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
    File.WriteAllText(output, generated);
}

static int Group(StringBuilder source, string group, string reflectionType, IEnumerable<MemberReference> definitions)
{
    var members = definitions.OrderBy(member => member.FullName, StringComparer.Ordinal).ToArray();
    if (members.Length == 0)
        return 0;

    source.AppendLine($"        public static class {group}")
        .AppendLine("        {");
    var names = new Identifiers(group, "Type");
    foreach (var overloads in members.GroupBy(MemberName, StringComparer.Ordinal))
    {
        var overloaded = overloads.Skip(1).Any();
        foreach (var member in overloads)
        {
            var name = overloaded ? overloads.Key + "__" + ParameterSuffix(member) : overloads.Key;
            var id = names.Take(name);
            source.AppendLine($"            /// <summary>{Xml(member.FullName)}</summary>")
                .AppendLine($"            public static readonly MemberBinding<{reflectionType}> {id} = new(Type, {Token(member)});");
        }
    }
    source.AppendLine("        }");
    return members.Length;
}

static string MemberName(MemberReference member) => member switch
{
    MethodDefinition { IsConstructor: true, IsStatic: true } => "StaticInitializer",
    MethodDefinition { IsConstructor: true } => "New",
    _ => member.Name
};

static string ParameterSuffix(MemberReference member)
{
    IEnumerable<ParameterDefinition> parameters = member switch
    {
        MethodDefinition method => method.Parameters,
        PropertyDefinition property => property.Parameters,
        _ => []
    };
    return parameters.Any() ? string.Join("_", parameters.Select(p => p.ParameterType.Name)) : "NoArgs";
}

static string Xml(string value) => SecurityElement.Escape(value)!;
static string Token(IMetadataTokenProvider definition) => $"0x{definition.MetadataToken.ToInt32():X8}";

internal class Identifiers(params string[] reserved)
{
    private readonly HashSet<string> used = new(reserved, StringComparer.Ordinal);

    public string Take(string name)
    {
        var stem = string.Concat(name.Select(c => char.IsAsciiLetterOrDigit(c) ? c : '_'));
        if (stem.Length == 0 || char.IsAsciiDigit(stem[0]))
            stem = "_" + stem;

        var id = stem;
        for (var suffix = 2; !used.Add(id); suffix++)
            id = stem + "_" + suffix;
        return "@" + id;
    }
}
